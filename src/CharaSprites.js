export function CharaSprite({ level, size = 160, silhouette = false }) {
  const scale = size / 32;

  if (silhouette) {
    const colors = [
      "#94A3B8","#7DD3FC","#818CF8","#8B5CF6","#C084FC",
      "#E879F9","#F472B6","#FB923C","#FBBF24","#F87171"
    ];
    const ph = makeSilhouettePlaceholder(colors[level - 1] || "#374151");
    return <PixelArt pixels={ph.pixels} palette={ph.palette} scale={scale} />;
  }

  switch(level) {
    case 1:  return <PixelArt pixels={EGG_PIXELS}      palette={EGG_PALETTE}      scale={scale} />;
    case 2:  return <PixelArt pixels={HINA_PIXELS}     palette={HINA_PALETTE}     scale={scale} />;
    case 3:  return <PixelArt pixels={KOFUKURO_PIXELS} palette={KOFUKURO_PALETTE} scale={scale} />;
    case 4:  return <PixelArt pixels={FUKUMIN_PIXELS}  palette={FUKUMIN_PALETTE}  scale={scale} />;
    case 5:  return <PixelArt pixels={FUKUMIN2_PIXELS} palette={FUKUMIN2_PALETTE} scale={scale} />;
    default: {
      const colors = ["","","","","","#E879F9","#F472B6","#FB923C","#FBBF24","#F87171"];
      const ph = makeSilhouettePlaceholder(colors[level - 1] || "#374151");
      return <PixelArt pixels={ph.pixels} palette={ph.palette} scale={scale} />;
    }
  }
}
